namespace("linkage", function ()
    set_languages("c++20")
    set_group("interop")

    target("component")
        set_default(false)
        set_kind("static")
        add_rules("@carven/carven")
        add_files("library.cv", "common.cv")
        add_defines("CARVEN_LINKAGE_VALUE=41")
    target_end()

    target("second")
        set_default(false)
        set_kind("static")
        add_rules("@carven/carven")
        add_files("second.cv", "common.cv")
        add_defines("CARVEN_LINKAGE_VALUE=73")
    target_end()

    target("app")
        set_default(false)
        set_kind("binary")
        add_deps("component", "second")
        add_rules("@carven/carven")
        add_files("app.cv", "main.cpp")
        add_tests("business")
    target_end()

    target("cpp")
        set_default(false)
        set_kind("binary")
        add_deps("component", "second")
        add_files("cpp_main.cpp")
        add_tests("business")
    target_end()
end)
